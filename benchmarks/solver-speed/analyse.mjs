// Statistics and figures of the solver-speed study from the runs bench.mjs
// recorded (one JSON line per solve). Plain JavaScript: an offline analysis
// of benchmark records, not app numerics.
//
// Statistics. Each (model, configuration) has n timed rounds. A factor's
// effect on one model is the ratio of the medians of two configurations that
// differ in that factor only; its 95 % confidence interval comes from a
// percentile bootstrap that resamples each configuration's rounds
// (10 000 resamples, seeded). Across models, effects are summarised by their
// geometric mean, with a bootstrap over models and rounds together.
//
// Usage: bun analyse.mjs <out-dir> <runs.jsonl> [<runs.jsonl> …]
//   writes <out-dir>/results.md and SVG figures

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const [outDir, ...files] = process.argv.slice(2);
if (!outDir || files.length === 0)
  throw new Error("usage: analyse.mjs <out-dir> <runs.jsonl> …");
mkdirSync(outDir, { recursive: true });

const rows = files
  .flatMap((f) =>
    readFileSync(f, "utf8")
      .split("\n")
      .filter(Boolean)
      .map((l) => ({ ...JSON.parse(l), file: f })),
  )
  .filter((r) => !r.warmup);

const modelKey = (r) => `${r.model} P${r.order} h=${r.h}`;
const median = (a) => {
  const s = [...a].sort((x, y) => x - y);
  const m = s.length >> 1;
  return s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2;
};
const geomean = (a) =>
  Math.exp(a.reduce((s, v) => s + Math.log(v), 0) / a.length);

// mulberry32, seeded: the bootstrap is reproducible.
function rng(seed) {
  let s = seed | 0;
  return () => {
    s = (s + 0x6d2b79f5) | 0;
    let t = Math.imul(s ^ (s >>> 15), 1 | s);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const resample = (a, rand) => a.map(() => a[Math.floor(rand() * a.length)]);
const percentile = (a, q) => {
  const s = [...a].sort((x, y) => x - y);
  return s[Math.min(s.length - 1, Math.max(0, Math.floor(q * s.length)))];
};
const B = 10000;

// group[runtime][model][config] = rows
const group = {};
for (const r of rows) {
  ((group[r.runtime] ??= {})[modelKey(r)] ??= {})[r.config] ??= [];
  group[r.runtime][modelKey(r)][r.config].push(r);
}

const metric = {
  total: (r) => r.totalMs,
  perIteration: (r) => r.phasesMs.iterations / r.iterations,
  assembly: (r) => r.phasesMs.assembly + (r.phasesMs.setupInputs ?? 0),
  setup: (r) => (r.phasesMs.setup ?? 0) + (r.phasesMs.eliminate ?? 0),
  iterations: (r) => r.iterations,
};

/** Ratio of medians a/b with a bootstrap CI, for one model. */
function ratio(aRows, bRows, m, rand) {
  const a = aRows.map(metric[m]);
  const b = bRows.map(metric[m]);
  const point = median(a) / median(b);
  const boot = [];
  for (let i = 0; i < B; i++)
    boot.push(median(resample(a, rand)) / median(resample(b, rand)));
  return { point, lo: percentile(boot, 0.025), hi: percentile(boot, 0.975) };
}

/** Geometric mean over models of the ratio a/b, bootstrap over models and rounds. */
function pooled(models, cfgA, cfgB, m, rand) {
  const pairs = models.map((mdl) => [
    mdl[cfgA].map(metric[m]),
    mdl[cfgB].map(metric[m]),
  ]);
  const point = geomean(pairs.map(([a, b]) => median(a) / median(b)));
  const boot = [];
  for (let i = 0; i < B; i++) {
    const pick = resample(pairs, rand);
    boot.push(
      geomean(
        pick.map(
          ([a, b]) => median(resample(a, rand)) / median(resample(b, rand)),
        ),
      ),
    );
  }
  return { point, lo: percentile(boot, 0.025), hi: percentile(boot, 0.975) };
}

const fmtR = ({ point, lo, hi }) =>
  `${point.toFixed(3)} [${lo.toFixed(3)}, ${hi.toFixed(3)}]`;
const fmtS = (ms) =>
  ms >= 1000 ? `${(ms / 1000).toFixed(2)} s` : `${ms.toFixed(0)} ms`;

const out = [];
out.push("# Solver-speed study: results", "");
out.push(
  "Generated by `analyse.mjs` from the run records. Times are medians of the timed rounds; " +
    "ratios are ratios of medians with 95 % percentile-bootstrap intervals in brackets. A ratio above 1 means the first configuration is slower.",
  "",
);

const rand = rng(12345);
for (const [runtime, models] of Object.entries(group)) {
  out.push(`## ${runtime}`, "");
  const keys = Object.keys(models).sort();
  const configs = [
    ...new Set(keys.flatMap((k) => Object.keys(models[k]))),
  ].sort();

  out.push("### Medians per model", "");
  out.push(
    `| Model | DOF | ${configs.map((c) => `${c} total (it)`).join(" | ")} |`,
    `| --- | ---: | ${configs.map(() => "---:").join(" | ")} |`,
  );
  for (const k of keys) {
    const any = Object.values(models[k])[0][0];
    const cells = configs.map((c) => {
      const rs = models[k][c];
      if (!rs) return "—";
      const t = rs.map(metric.total);
      return `${fmtS(median(t))} (${median(rs.map(metric.iterations))}) n=${rs.length}, ${fmtS(Math.min(...t))}–${fmtS(Math.max(...t))}`;
    });
    out.push(`| ${k} | ${any.dofs} | ${cells.join(" | ")} |`);
  }
  out.push("");

  const has = (...cs) => keys.filter((k) => cs.every((c) => models[k][c]));
  const factor = (title, a, b, m) => {
    const ks = has(a, b);
    if (!ks.length) return;
    out.push(`### ${title}: ${a} / ${b} (${m})`, "");
    out.push("| Model | Ratio [95 % CI] |", "| --- | ---: |");
    for (const k of ks)
      out.push(
        `| ${k} | ${fmtR(ratio(models[k][a], models[k][b], m, rand))} |`,
      );
    out.push(
      `| **Geometric mean over ${ks.length} models** | **${fmtR(
        pooled(
          ks.map((k) => models[k]),
          a,
          b,
          m,
          rand,
        ),
      )}** |`,
      "",
    );
  };
  factor("Asyncify at -O2", "mfem:A-shipped", "mfem:B-O2-noasync", "total");
  factor("Asyncify at -O3", "mfem:C-O3-async", "mfem:D-O3-noasync", "total");
  factor(
    "-O2 against -O3, with Asyncify",
    "mfem:A-shipped",
    "mfem:C-O3-async",
    "total",
  );
  factor(
    "-O2 against -O3, without Asyncify",
    "mfem:B-O2-noasync",
    "mfem:D-O3-noasync",
    "total",
  );
  factor(
    "C++/MFEM against Rust, Gauss–Seidel",
    "mfem:A-shipped",
    "rust-gs",
    "total",
  );
  factor(
    "C++/MFEM against Rust, time per iteration",
    "mfem:A-shipped",
    "rust-gs",
    "perIteration",
  );
  factor(
    "C++/MFEM against Rust, assembly",
    "mfem:A-shipped",
    "rust-gs",
    "assembly",
  );
  factor(
    "Iterations, C++/MFEM against Rust (stopping rules differ)",
    "mfem:A-shipped",
    "rust-gs",
    "iterations",
  );
  factor("Gauss–Seidel against AMG, Rust", "rust-gs", "rust-amg", "total");
  factor(
    "Shipped C++ against Rust AMG (the change users saw)",
    "mfem:A-shipped",
    "rust-amg",
    "total",
  );

  // Phase breakdown of the medians.
  out.push("### Phases (medians)", "");
  out.push(
    "| Model | Configuration | Assembly | Setup | Iterations | Per iteration | Other |",
    "| --- | --- | ---: | ---: | ---: | ---: | ---: |",
  );
  for (const k of keys)
    for (const c of configs) {
      const rs = models[k][c];
      if (!rs) continue;
      const asm = median(rs.map(metric.assembly));
      const setup = median(rs.map(metric.setup));
      const it = median(rs.map((r) => r.phasesMs.iterations));
      const tot = median(rs.map(metric.total));
      out.push(
        `| ${k} | ${c} | ${fmtS(asm)} | ${fmtS(setup)} | ${fmtS(it)} | ${median(rs.map(metric.perIteration)).toFixed(2)} ms | ${fmtS(Math.max(0, tot - asm - setup - it))} |`,
      );
    }
  out.push("");

  // Figure: iterations and time against DOFs, GS vs AMG (and MFEM where run).
  const scaling = keys.map((k) => ({ k, m: models[k] }));
  writeFileSync(
    join(outDir, `scaling-${runtime.split(" ")[0]}.svg`),
    scalingFigure(scaling, configs),
  );
}
writeFileSync(join(outDir, "results.md"), out.join("\n") + "\n");
console.log(`wrote ${join(outDir, "results.md")}`);

// ── Figure ────────────────────────────────────────────────────────────────────

function scalingFigure(scaling, configs) {
  const W = 760,
    H = 320,
    P = { l: 56, r: 150, t: 28, b: 44 };
  const pw = (W - P.l - P.r) / 2 - 20,
    ph = H - P.t - P.b;
  const colours = {
    "mfem:A-shipped": "#c2410c",
    "rust-gs": "#7c3aed",
    "rust-amg": "#0f766e",
  };
  const names = {
    "mfem:A-shipped": "C++/MFEM, Gauss–Seidel (v0.6)",
    "rust-gs": "Rust, Gauss–Seidel",
    "rust-amg": "Rust, AMG (v0.7)",
  };
  const shown = configs.filter((c) => colours[c]);
  const pts = (c, m) =>
    scaling
      .filter(({ m: mm }) => mm[c])
      .map(({ m: mm }) => ({
        x: mm[c][0].dofs,
        y: median(mm[c].map(metric[m])),
        model: mm[c][0].model,
      }));
  const panel = (ox, m, label) => {
    const all = shown.flatMap((c) => pts(c, m));
    const lx = (v) => Math.log10(v);
    const [x0, x1] = [
      Math.floor(lx(Math.min(...all.map((p) => p.x)))),
      Math.ceil(lx(Math.max(...all.map((p) => p.x)))),
    ];
    const [y0, y1] = [
      Math.floor(lx(Math.min(...all.map((p) => p.y)))),
      Math.ceil(lx(Math.max(...all.map((p) => p.y)))),
    ];
    const X = (v) => ox + ((lx(v) - x0) / (x1 - x0)) * pw;
    const Y = (v) => P.t + ((y1 - lx(v)) / (y1 - y0)) * ph;
    let s = "";
    for (let e = x0; e <= x1; e++)
      s += `<line x1="${X(10 ** e)}" x2="${X(10 ** e)}" y1="${P.t}" y2="${P.t + ph}" stroke="#e5e7eb"/><text x="${X(10 ** e)}" y="${P.t + ph + 16}" font-size="11" text-anchor="middle" fill="#6b7280">10${sup(e)}</text>`;
    for (let e = y0; e <= y1; e++)
      s += `<line x1="${ox}" x2="${ox + pw}" y1="${Y(10 ** e)}" y2="${Y(10 ** e)}" stroke="#e5e7eb"/><text x="${ox - 6}" y="${Y(10 ** e) + 4}" font-size="11" text-anchor="end" fill="#6b7280">10${sup(e)}</text>`;
    for (const c of shown)
      for (const p of pts(c, m))
        s += `<circle cx="${X(p.x).toFixed(1)}" cy="${Y(p.y).toFixed(1)}" r="3.5" fill="${colours[c]}" opacity="0.85"><title>${p.model}: ${p.x} DOF, ${p.y.toFixed(1)}</title></circle>`;
    s += `<text x="${ox}" y="${P.t - 10}" font-size="12" fill="#374151">${label}</text><text x="${ox + pw}" y="${H - 6}" font-size="11" text-anchor="end" fill="#6b7280">degrees of freedom</text>`;
    return s;
  };
  let legend = "";
  shown.forEach((c, i) => {
    legend += `<circle cx="${W - P.r + 16}" cy="${P.t + 10 + 18 * i}" r="4" fill="${colours[c]}"/><text x="${W - P.r + 26}" y="${P.t + 14 + 18 * i}" font-size="11" fill="#374151">${names[c]}</text>`;
  });
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" font-family="system-ui, sans-serif"><rect width="${W}" height="${H}" fill="#fff"/>${panel(P.l, "iterations", "CG iterations")}${panel(P.l + pw + 60, "total", "solve time (ms)")}${legend}</svg>\n`;
}

function sup(e) {
  const d = {
    "-": "⁻",
    0: "⁰",
    1: "¹",
    2: "²",
    3: "³",
    4: "⁴",
    5: "⁵",
    6: "⁶",
    7: "⁷",
    8: "⁸",
    9: "⁹",
  };
  return String(e)
    .split("")
    .map((c) => d[c])
    .join("");
}
